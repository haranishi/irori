// 既知の不具合（C1 報告に、再現の手順つきで書いたもの）を試験でどう扱うか。
// test.fail は使わない（前提の手順が壊れても「予想どおりの失敗」として隠れるため）。前提はふつうに確かめ、
// 不具合の箇所だけ「いまの振る舞い」を確かめる。直ったらその確かめが赤くなるので、契約の形に書き換える。
export function changed(n: number, contract: string): string {
  return `既知の不具合${n}（C1 報告）の振る舞いが変わった。直したのなら、この試験を契約（${contract}）を確かめる形に書き換える`;
}
